-- =====================================================
-- TABLA store_prices: Precios por tienda para items del mercado
-- =====================================================

-- Crear tabla
CREATE TABLE IF NOT EXISTS store_prices (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  item_name TEXT NOT NULL,
  store TEXT NOT NULL CHECK (store IN ('exito', 'd1', 'jumbo', 'carulla', 'euro')),
  price INTEGER NOT NULL CHECK (price > 0),
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  UNIQUE (item_name, store)
);

-- Indice para busquedas por item
CREATE INDEX IF NOT EXISTS idx_store_prices_item_name ON store_prices (item_name);

-- Indice para busquedas por tienda
CREATE INDEX IF NOT EXISTS idx_store_prices_store ON store_prices (store);

-- Habilitar RLS
ALTER TABLE store_prices ENABLE ROW LEVEL SECURITY;

-- Politica de lectura publica (precios son informacion publica)
CREATE POLICY "store_prices_select" ON store_prices
  FOR SELECT USING (true);

-- Politica de insercion (solo usuarios autenticados o servicio)
CREATE POLICY "store_prices_insert" ON store_prices
  FOR INSERT WITH CHECK (true);

-- Politica de actualizacion
CREATE POLICY "store_prices_update" ON store_prices
  FOR UPDATE USING (true);

-- Trigger para updated_at
CREATE OR REPLACE FUNCTION update_store_prices_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER store_prices_updated_at_trigger
  BEFORE UPDATE ON store_prices
  FOR EACH ROW
  EXECUTE FUNCTION update_store_prices_updated_at();

