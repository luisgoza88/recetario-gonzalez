// Recipe Library - Scalable Recipes with Base Servings of 3
// Each ingredient has a baseAmount that scales with servings

export interface ScalableIngredient {
  name: string;
  baseAmount: number; // Amount for 3 servings
  unit: string;
  scalable: boolean; // Some ingredients don't scale (e.g., "1 bay leaf")
  optional?: boolean;
  notes?: string;
}

export interface RecipeStep {
  order: number;
  instruction: string;
  duration?: number; // minutes
  tip?: string;
}

export interface LibraryRecipe {
  id: string;
  name_es: string;
  name_en: string;
  description: string;
  category: 'breakfast' | 'lunch' | 'dinner' | 'dessert' | 'side';
  cuisine_type: string;
  baseServings: 3;
  prepTime: number; // minutes
  cookTime: number; // minutes
  difficulty: 'easy' | 'medium' | 'hard';
  ingredients: ScalableIngredient[];
  steps: RecipeStep[];
  tips?: string[];
  tags: string[];
  imageMatch?: string; // name_en from image library for matching
}

// Helper function to scale ingredients
export function scaleIngredients(
  ingredients: ScalableIngredient[],
  targetServings: number,
  baseServings: number = 3
): ScalableIngredient[] {
  const ratio = targetServings / baseServings;

  return ingredients.map(ing => ({
    ...ing,
    baseAmount: ing.scalable
      ? Math.round(ing.baseAmount * ratio * 100) / 100
      : ing.baseAmount
  }));
}

// Format ingredient for display
export function formatIngredient(ing: ScalableIngredient): string {
  const amount = ing.baseAmount;
  const unit = ing.unit;
  const name = ing.name;

  if (amount === 0) return name;

  // Handle fractions for common amounts
  let displayAmount: string;
  if (amount === 0.25) displayAmount = '¼';
  else if (amount === 0.5) displayAmount = '½';
  else if (amount === 0.75) displayAmount = '¾';
  else if (amount === 0.33) displayAmount = '⅓';
  else if (amount === 0.66) displayAmount = '⅔';
  else if (amount % 1 === 0) displayAmount = amount.toString();
  else displayAmount = amount.toFixed(1);

  if (unit === 'unit' || unit === 'units') {
    return `${displayAmount} ${name}`;
  }

  return `${displayAmount} ${unit} ${name}`;
}

