// Helper: obtener recetas por categoría
export function getRecipesByCategory(
  category: RecipeCategory,
): ExpandedRecipe[] {
  return expandedRecipes.filter((r) => r.category === category);
}

// Helper: obtener nombres de recetas para prompt de IA
export function getRecipeNamesForPrompt(): string[] {
  return expandedRecipes.map((r) => {
    const badges: string[] = [];
    if (r.thermomixCompatible) badges.push("TM6");
    if (r.category === "fitness") badges.push("💪");
    if (r.category === "rapida") badges.push("⚡");
    const suffix = badges.length > 0 ? ` [${badges.join(",")}]` : "";
    return `${r.name} (${r.category})${suffix}`;
  });
}

// Helper: buscar recetas por texto
export function searchExpandedRecipes(query: string): ExpandedRecipe[] {
  const q = query.toLowerCase();
  return expandedRecipes.filter(
    (r) =>
      r.name.toLowerCase().includes(q) ||
      r.tags?.some((t) => t.toLowerCase().includes(q)) ||
      r.ingredients.some((i) => i.name.toLowerCase().includes(q)),
  );
}
