type SubcategoryMap = {
  [key: string]: {
    id: string;
    name: string;
    icon: string;
    keywords: string[];
  };
};

/**
 * Busca el icono correcto dentro de un mapa de subcategorías
 */
function findIconInSubcategories(
  productName: string,
  subcategories: SubcategoryMap,
  defaultIcon: string,
): string {
  const nameLower = productName.toLowerCase();

  for (const [, subcategory] of Object.entries(subcategories)) {
    if (subcategory.keywords.some((keyword) => nameLower.includes(keyword))) {
      return subcategory.icon;
    }
  }

  return defaultIcon;
}

