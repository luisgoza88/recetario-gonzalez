/**
 * Determina si una categoría es de proteínas
 */
export function isProteinCategory(
  categoryId?: string,
  categoryName?: string,
): boolean {
  if (categoryId === "proteins") return true;
  if (categoryName?.toLowerCase().includes("proteína")) return true;
  if (categoryName?.toLowerCase().includes("protein")) return true;
  return false;
}

/**
 * Obtiene la función de icono correspondiente a una categoría
 */
function getIconFunctionForCategory(
  categoryId?: string,
  categoryName?: string,
): ((name: string) => string) | null {
  // Primero buscar por ID
  if (categoryId) {
    const idLower = categoryId.toLowerCase();
    if (CATEGORY_ICON_FUNCTIONS[idLower]) {
      return CATEGORY_ICON_FUNCTIONS[idLower];
    }
  }

  // Luego buscar por nombre
  if (categoryName) {
    const nameLower = categoryName.toLowerCase();
    for (const [key, func] of Object.entries(CATEGORY_ICON_FUNCTIONS)) {
      if (nameLower.includes(key)) {
        return func;
      }
    }
  }

  return null;
}

/**
 * Obtiene el icono correcto para un item, usando subcategorías cuando corresponda
 * @param itemName - Nombre del item
 * @param categoryId - ID de la categoría
 * @param categoryName - Nombre de la categoría
 * @param defaultIcon - Icono por defecto de la categoría
 * @returns Emoji correcto para el item
 */
export function getItemIcon(
  itemName: string,
  categoryId?: string,
  categoryName?: string,
  defaultIcon?: string,
): string {
  // Buscar función de icono específica para la categoría
  const iconFunction = getIconFunctionForCategory(categoryId, categoryName);

  if (iconFunction) {
    return iconFunction(itemName);
  }

  // Si no hay función específica, usar el icono default
  return defaultIcon || "📦";
}

/**
 * Obtiene el icono inteligente basado solo en el nombre del producto
 * (útil cuando no se conoce la categoría)
 */
export function getSmartIcon(productName: string): string {
  const nameLower = productName.toLowerCase();

  // Orden de prioridad para buscar coincidencias
  const searchOrder: [SubcategoryMap, string][] = [
    [PROTEIN_SUBCATEGORIES, "🥩"],
    [VEGETABLE_SUBCATEGORIES, "🥬"],
    [TUBER_SUBCATEGORIES, "🥔"],
    [FRUIT_SUBCATEGORIES, "🍎"],
    [DAIRY_SUBCATEGORIES, "🧀"],
    [GRAIN_SUBCATEGORIES, "🍚"],
    [PANTRY_SUBCATEGORIES, "🫙"],
    [SPICE_SUBCATEGORIES, "🧂"],
    [BEVERAGE_SUBCATEGORIES, "🥤"],
    [FROZEN_SUBCATEGORIES, "❄️"],
    [SNACK_SUBCATEGORIES, "🍿"],
    [BAKERY_SUBCATEGORIES, "🥖"],
    [HOUSEHOLD_SUBCATEGORIES, "🧹"],
    [PET_FOOD_SUBCATEGORIES, "🐾"],
  ];

  for (const [subcategories] of searchOrder) {
    for (const [, subcategory] of Object.entries(subcategories)) {
      if (subcategory.keywords.some((keyword) => nameLower.includes(keyword))) {
        return subcategory.icon;
      }
    }
  }

  return "📦";
}
